"""
make_reports.py - writes the Phase 3 reports into reports/ from the saved results.
Usage: python make_reports.py --exp <main experiment> --method <reconciliation method>
"""
from __future__ import annotations

import argparse
import datetime as dt
import json

import numpy as np
import pandas as pd

from common import BT, CONFIG, DATA, FC, MODELS, REPORTS, SC, md_table, origins
from evaluate import load, metrics, select
from models import DESCRIPTION

TODAY = dt.date.today().isoformat()
SCOPE = ("> **Scope.** All results refer to **domestic conventional generation monitored by CEA** (coal, lignite, gas, diesel, "
         "nuclear, large hydro). Solar, wind, small hydro and biomass are excluded (no authorised generation data); "
         "the figures therefore do **not** represent total Indian electricity production. Bhutan import is modelled separately.\n")
LEVEL_ORDER = ["National", "Regions (5)", "National sources", "States group A", "States group B", "States group C",
               "State x source (eligible)", "State x source (ineligible)", "Bhutan import (separate)"]


def order(df, col="level_cat"):
    df = df.copy()
    df["_o"] = df[col].map({k: i for i, k in enumerate(LEVEL_ORDER)}).fillna(99)
    return df.sort_values(["_o"] + [c for c in df.columns if c in ("MASE",)]).drop(columns="_o")


def header(title):
    return f"# {title}\n\n_Generated by `src/make_reports.py` on {TODAY}._\n\n{SCOPE}\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exp", required=True)
    ap.add_argument("--method", required=True)
    a = ap.parse_args()
    d = load()
    main_d = d[d.experiment == a.exp]
    sel = select(d, a.exp)
    sel.to_csv(MODELS / f"selected_models_{a.exp}.csv", index=False)
    allm = metrics(main_d, ["level_cat", "model"])
    allm.to_csv(BT / f"metrics_by_level_model_{a.exp}.csv", index=False)
    hm = metrics(main_d[main_d.h.isin(CONFIG["report_horizons"])], ["level_cat", "model", "h"])
    hm.to_csv(BT / f"metrics_by_level_model_horizon_{a.exp}.csv", index=False)
    for e in d.experiment.unique():
        metrics(d[d.experiment == e], ["level_cat", "model"]).to_csv(BT / f"metrics_by_level_model_{e}.csv", index=False)

    # ------------------------------------------------------------------ model_comparison.md
    mase = allm.pivot(index="level_cat", columns="model", values="MASE")
    mase = mase.reindex([l for l in LEVEL_ORDER if l in mase.index])
    cols = [c for c in ["naive", "snaive", "lintrend", "lintrend_season", "ses", "holt_damped", "hw_add", "hw_mul", "ets_auto", "arima", "sarima", "rf", "xgb"] if c in mase]
    wape = allm.pivot(index="level_cat", columns="model", values="WAPE_%").reindex(mase.index)[cols]
    orders = pd.read_csv(MODELS / f"orders_{a.exp}.csv") if (MODELS / f"orders_{a.exp}.csv").exists() else pd.DataFrame()
    ordsum = orders[orders.node_id.isin(["TOTAL"]) | orders.node_id.str.startswith("REG|")] if len(orders) else orders
    fi = pd.read_csv(MODELS / f"ml_feature_importance_{a.exp}.csv") if (MODELS / f"ml_feature_importance_{a.exp}.csv").exists() else pd.DataFrame()
    fi_t = fi.sort_values("importance", ascending=False).groupby("model").head(8)[["model", "feature", "importance"]] if len(fi) else fi
    grpC = allm[allm.level_cat == "States group C"].sort_values("MASE")[["model", "MASE", "WAPE_%", "bias_%"]]
    hmet = pd.read_csv(BT / f"hier_metrics_{a.exp}.csv")
    cdir = hmet[(hmet.level_cat == "States group C") & hmet.method.isin(["BASE", a.method])][["method", "MASE", "WAPE_%", "bias_%"]]
    txt = header("Model Comparison") + f"""Main experiment: **{a.exp}** (see `covid_sensitivity.md`). Selection rule: {CONFIG['selection_metric']}; the selected model must beat seasonal-naive.
Metrics are **out-of-sample** rolling-origin results (h = 1..12 pooled). MASE < 1 means better than the in-sample seasonal-naive error scale.

## 1. Selected model per forecasting level
{md_table(order(sel)[['level_cat', 'selected_model', 'description', 'MASE', 'WAPE_%', 'best_baseline', 'baseline_MASE', 'improvement_vs_best_baseline_%', 'runner_up']])}

## 2. MASE by level and model (lower is better; baselines first)
{md_table(mase[cols].reset_index(), '{:.3f}')}

## 3. WAPE % by level and model
{md_table(wape.reset_index(), '{:.2f}')}

## 4. Baseline vs advanced
{md_table(order(sel)[['level_cat', 'best_baseline', 'baseline_MASE', 'selected_model', 'MASE', 'improvement_vs_best_baseline_%']])}

## 5. Statistical model parameters
- Holt-Winters / Holt: damped additive trend; seasonal period 12; parameters estimated by maximum likelihood at each origin.
- ETS: automatic selection per origin by AICc over error {{A, M}} x trend {{N, Ad}} x seasonality {{A, M}} (multiplicative only for strictly positive series).
- ARIMA / SARIMA: order selected by AIC on the first-origin training window per series and experiment, then held fixed and re-estimated at every origin (prevents per-origin overfitting, keeps cost manageable). Seasonal differencing D=1 at lag 12 for SARIMA. Experiment A adds the COVID (Mar-May 2020) 0/1 regressor.
- Selected orders (national and regional):
{md_table(ordsum)}
Full list: `outputs/models/orders_{a.exp}.csv`.

## 6. Machine-learning models
Global models pooled across all {main_d.node_id.nunique()} series (scale-free target log1p(y[t+h]) - log1p(y[t+h-12]); one model per origin, horizons 1-12 as a feature).
Features (computed only from data up to the origin): horizon, last YoY log-change, mean YoY over 3/6 months, YoY std over 6 months, level vs seasonal reference, rolling mean ratios (3 vs 12 months), rolling std (12), zero-share, target month (sin/cos and integer), year, series level, and in experiment A COVID indicators (target, reference month, recent window). No capacity, consumption, population or GSDP.
RF: {CONFIG['rf_params']}; XGBoost: {CONFIG['xgb_params']} (xgboost 3.4.1).
Top feature importances (last origin):
{md_table(fi_t, '{:.3f}')}

## 7. Group C states: direct models vs regional allocation
Direct models (backtest):
{md_table(grpC.head(6))}
Allocation of the regional forecast by seasonal proportion (hierarchical backtest, BASE = allocation before reconciliation):
{md_table(cdir)}

## 8. Why each final model was selected
""" + "\n".join((f"- **{r.level_cat}: {r.selected_model}**. Lowest out-of-sample mean MASE ({r.MASE:.3f}) among models with full coverage; "
                f"beats the best baseline ({r.best_baseline}, MASE {r.baseline_MASE:.3f}) by {r.improvement_vs_best_baseline_pct:.1f}%; runner-up {r.runner_up}.")
               if r.selected_model != "snaive" else
               (f"- **{r.level_cat}: snaive**. No model beats the seasonal-naive benchmark (MASE {r.MASE:.3f}) out of sample; best alternative {r.runner_up}. "
                f"The benchmark is kept (simplest adequate model).")
               for r in order(sel).rename(columns={'improvement_vs_best_baseline_%': 'improvement_vs_best_baseline_pct'}).itertuples()) + "\n"
    (REPORTS / "model_comparison.md").write_text(txt, encoding="utf-8")

    # ------------------------------------------------------------------ backtesting_report.md
    bh = hm.pivot_table(index=["level_cat", "model"], columns="h", values="MASE").reset_index()
    bw = hm.pivot_table(index=["level_cat", "model"], columns="h", values="WAPE_%").reset_index()
    keep = set(sel.selected_model) | {"snaive", "naive", "lintrend", "ets_auto", "sarima", "xgb", "rf"}
    bh = order(bh[bh.model.isin(keep)])
    bw = order(bw[bw.model.isin(keep)])
    full = order(allm)[["level_cat", "model", "n", "MAE", "RMSE", "WAPE_%", "MASE", "bias_%", "coverage"]]
    nodes_n = main_d.groupby("level_cat").node_id.nunique().rename("series").reset_index()
    txt = header("Backtesting Report") + f"""## Design
- Expanding window; training always starts at the experiment start ({a.exp}: {CONFIG['experiment_B_start'] if a.exp == 'B' else CONFIG['main_data_start']}) and ends at the origin. Strict chronological order; no random splits.
- Origins: monthly {origins('monthly')[0]}..{origins('monthly')[-1]} ({len(origins('monthly'))} origins) for national, regional, national-source and import series; quarterly {origins('quarterly')[0]}..{origins('quarterly')[-1]} ({len(origins('quarterly'))} origins) for states and state x source.
- Each origin forecasts h = 1..12; only targets with observed actuals (<= {CONFIG['main_data_end']}) are scored. Reported horizons: 1, 3, 6, 12.
- Metrics: MAE, RMSE (GWh), WAPE = sum|e|/sum|y| (pooled, robust to zeros), MASE = |e| / in-sample seasonal-naive MAE of the training window (rows with zero scale excluded), bias = sum(f-y)/sum(y) (positive = over-forecast). MAPE is not used because of zero values in state x source series.
- Series per level: {', '.join(f'{r.level_cat}: {r.series}' for r in order(nodes_n).itertuples())}.

## MASE by horizon (selected models and key benchmarks)
{md_table(bh, '{:.3f}')}

## WAPE % by horizon
{md_table(bw, '{:.2f}')}

## All models, all metrics (h = 1..12 pooled)
{md_table(full)}

Raw forecasts: `outputs/backtesting/forecasts_<exp>.csv`; metrics: `outputs/backtesting/metrics_*.csv`.
"""
    (REPORTS / "backtesting_report.md").write_text(txt, encoding="utf-8")

    # ------------------------------------------------------------------ covid_sensitivity.md
    common_o = origins("monthly")
    qset = set(origins("quarterly"))
    cv = d[d.experiment.isin(["A", "B", "C"]) & d.origin.isin(qset)]  # common quarterly origins for all three
    cm = metrics(cv, ["experiment", "level_cat", "model"])
    piv = cm.pivot_table(index=["level_cat", "model"], columns="experiment", values="MASE").reset_index()
    best_by_exp = cm[cm.coverage >= 0.95].sort_values("MASE").groupby(["experiment", "level_cat"]).head(1)
    bb = best_by_exp.pivot(index="level_cat", columns="experiment", values="MASE").reset_index()
    bm = best_by_exp.pivot(index="level_cat", columns="experiment", values="model").reset_index()
    reg_models = piv[piv.model.isin(["lintrend_season", "sarima", "arima", "rf", "xgb", "ets_auto", "hw_mul", "snaive"])]
    selA, selB, selC = (select(cv, e) for e in ("A", "B", "C"))
    txt = header("COVID Sensitivity") + f"""## Experiments (identical origins, horizons and metrics)
- **A**: full history 2019-07 onward + COVID intervention (Mar-May 2020). The regressor enters linear-trend, ARIMA/SARIMA (exogenous dummy) and RF/XGBoost (indicator features); smoothing models (SES/Holt/HW/ETS) and naive models cannot take regressors, so for them A = C.
- **B**: training starts FY2021-22 (2021-04); no COVID months in sample (shorter history: {len(pd.period_range('2021-04', origins('monthly')[0], freq='M'))} months at the first origin).
- **C**: full history, no intervention (benchmark).
No observation was deleted in A or C; B discards 21 genuine months by design (sensitivity only).

## Best model and MASE per level, by experiment
{md_table(order(bm.merge(bb, on='level_cat', suffixes=('_model', '_MASE'))), '{:.3f}')}

## Selected model per experiment
{md_table(order(selA[['level_cat', 'selected_model', 'MASE']].merge(selB[['level_cat', 'selected_model', 'MASE']], on='level_cat', suffixes=('_A', '_B')).merge(selC[['level_cat', 'selected_model', 'MASE']].rename(columns={'selected_model': 'selected_model_C', 'MASE': 'MASE_C'}), on='level_cat')), '{:.3f}')}

## MASE of regressor-capable and key models by experiment
{md_table(order(reg_models), '{:.3f}')}

## Conclusion
- Differences between experiments are small (best-model MASE within about +/-0.04 at every level) and not one-directional: A is better nationally; B is slightly better for regions and states; C is never better than A.
- The intervention regressor improves the models that can use it (linear trend + month dummies, SARIMA); ML is insensitive (it can learn the anomaly from lag features).
- **Main experiment: A** - it keeps all genuine observations (no unjustified deletion), is best at the national level, and preserves the longest history for long-run trend estimation. B is a documented sensitivity; its regional/state gains are within backtest noise (13 quarterly origins).
- The comparison uses the 13 common quarterly origins (ML in B and C was refitted only at these origins to save compute). A's full monthly-origin results are used for model selection elsewhere.
"""
    (REPORTS / "covid_sensitivity.md").write_text(txt, encoding="utf-8")
    from report_part2 import part2
    part2(a, d, sel)
    print("reports written")


if __name__ == "__main__":
    main()
